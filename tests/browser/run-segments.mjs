import assert from 'node:assert/strict';
const playwright = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await playwright.webkit.launch({ headless: true, executablePath: process.env.BROWSER_PATH });
const page = await browser.newPage({ viewport: { width: 1300, height: 850 } });
const errors = [];
page.on('pageerror', error => errors.push(String(error)));
const word = index => page.locator(`.wave-transcript-editor [data-word-id="w${index}"]`);
const wait = predicate => page.waitForFunction(predicate);
const view = async name => { await page.getByRole('button', { name, exact: true }).click(); };
try {
  await page.goto('http://localhost:1420/tests/fixtures/editor.html');
  await wait(() => window.editorApi?.()?.editingState().ready);
  await view('Segments');
  assert.equal(await page.locator('.wave-segment').first().locator('[data-word-id]').count(), 12);
  await page.getByRole('button', { name: 'Select segment at 0:01', exact: true }).click();
  assert.equal(await page.getByLabel('Selection start in seconds').inputValue(), '1.000');
  assert.equal(await page.getByLabel('Selection end in seconds').inputValue(), '6.800');
  assert.equal(await page.locator('.wave-word--selected').count(), 12);
  await page.getByLabel('Selection end in seconds').fill('1.001');
  await page.getByLabel('Selection end in seconds').press('Enter');
  await page.getByRole('button', { name: 'Select segment at 0:01', exact: true }).click();
  assert.equal(await page.getByLabel('Selection end in seconds').inputValue(), '6.800', 'repeated segment selection overrides a waveform trim');
  await view('Flow');
  assert.equal(await page.locator('.wave-word--selected').count(), 12);
  await view('Segments');
  assert.equal(await page.locator('.wave-word--selected').count(), 12);
  // A real drag must not be replaced by the click at its final word.
  const start = await word(2).boundingBox(), end = await word(5).boundingBox();
  await page.mouse.move(start.x + 1, start.y + start.height / 2); await page.mouse.down();
  await page.mouse.move(end.x + end.width - 1, end.y + end.height / 2, { steps: 12 }); await page.mouse.up();
  assert.equal(await page.getByLabel('Selection start in seconds').inputValue(), '2.000');
  assert.equal(await page.getByLabel('Selection end in seconds').inputValue(), '3.800');
  await page.keyboard.press('Backspace');
  await wait(() => document.querySelector('[data-word-id="w2"]')?.dataset.audioState === 'removed');
  for (const index of [2, 3, 4, 5]) assert.equal(await word(index).getAttribute('data-audio-state'), 'removed');
  assert.equal(await word(6).getAttribute('data-audio-state'), 'kept');
  await view('Flow');
  assert.equal(await word(3).getAttribute('data-audio-state'), 'removed');
  await page.locator('.wave-timeline').focus(); await page.keyboard.press('Meta+z');
  await wait(() => document.querySelector('[data-word-id="w3"]')?.dataset.audioState === 'kept');
  await view('Segments');
  // Added pauses, their duration menus and rebuilds share the same document.
  await word(5).click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Add pause after', exact: true }).hover();
  await page.getByRole('menuitem', { name: '0.5 s', exact: true }).click();
  await page.locator('.wave-segments .wave-word--pause-token').waitFor();
  assert.equal(await page.locator('.wave-pause-pill').innerText(), '+0.5 s ▾');
  await page.locator('.wave-segments .wave-word--pause-token').click();
  await page.getByRole('menuitem', { name: '2 s', exact: true }).click();
  assert.equal(await page.locator('.wave-pause-pill').innerText(), '+2 s ▾');
  await view('Flow');
  assert.equal(await page.locator('.wave-word--pause-token').innerText(), '+2 s');
  await view('Segments');
  assert.equal(await page.locator('.wave-word--pause-token').innerText(), '+2 s');
  await word(5).click();
  await page.getByLabel('Selection end in seconds').fill('3.501');
  await page.getByLabel('Selection end in seconds').press('Enter');
  await page.getByRole('button', { name: 'Cut audio', exact: true }).click();
  await wait(() => document.querySelector('[data-word-id="w5"]')?.dataset.audioState === 'partial');
  await view('Flow'); assert.equal(await word(5).getAttribute('data-audio-state'), 'partial');
  await view('Segments'); assert.equal(await word(5).getAttribute('data-audio-state'), 'partial');
  // Switching views while paused also restores the current-word highlight.
  await word(10).click();
  await wait(() => document.querySelector('[data-word-id="w10"]')?.classList.contains('wave-word--active'));
  await view('Flow'); assert(await word(10).evaluate(el => el.classList.contains('wave-word--active')));
  await view('Segments'); assert(await word(10).evaluate(el => el.classList.contains('wave-word--active')));
  await page.locator('.wave-editor-scroll').focus(); await page.keyboard.press('Enter');
  await page.getByRole('textbox', {name:'Correct word',exact:true}).fill('corrected');
  await page.getByRole('textbox', {name:'Correct word',exact:true}).press('Enter');
  await wait(() => document.querySelector('[data-word-id="w10"]')?.textContent === 'corrected');
  assert(await word(10).evaluate(el => el.classList.contains('wave-word--selected') && el.classList.contains('wave-word--active')),
    'correction rebuild keeps both current word and selection');
  const segmentButton = page.getByRole('button', { name: 'Select segment at 0:01', exact: true });
  await segmentButton.focus(); await page.keyboard.press('Enter');
  assert.equal(await page.locator('.wave-word--selected').count(), 12, 'segment selection works from the keyboard');
  await word(10).click();
  await page.getByRole('button', { name: 'Play', exact: true }).click();
  await wait(() => document.querySelector('[data-word-id="w12"]')?.classList.contains('wave-word--active'));
  await view('Flow');
  assert.equal(await page.locator('.wave-word--active').count(), 1, 'Flow follows playback after switching views');
  await view('Segments');
  assert.equal(await page.locator('.wave-word--active').count(), 1, 'Segments follows playback after switching views');
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  assert.deepEqual(errors, []);
  console.log('Segments checks passed: drag/cut/undo, segment selection, cross-view highlights, pause controls and exact waveform trims.');
} catch (error) {
  await page.screenshot({ path: '/private/tmp/wave-segments-failure.png' });
  console.log('Page errors:', errors);
  throw error;
} finally { await browser.close(); }
